"""Render the Lunar Eclipse Forge logo (assets/logo.jpg, dark on light) to a C header: cropped to the
mark, coverage 0..15, rows top to bottom, 2 pixels per byte (high nibble first), as the font's glyphs.
Two sizes: LOGO_* (100 px tall) for the boot screen (gfx.c draw_splash), LOGO_S* (72) for HOME's
corona (ui.c draw_corona_home).
"""
import sys
from pathlib import Path

from PIL import Image, ImageOps

SRC = Path(__file__).resolve().parents[1] / "assets" / "logo.jpg"
SIZES = (("LOGO", 100), ("LOGO_S", 72))


def bitmap(im, name, h):
    w = round(im.width * h / im.height)
    sm = im.resize((w, h), Image.LANCZOS)
    px = sm.load()
    bpr = (w + 1) // 2
    data = bytearray()
    for y in range(h):
        row = [min(15, (px[x, y] + 8) // 17) for x in range(w)] + [0]
        data += bytes((row[x] << 4) | row[x + 1] for x in range(0, bpr * 2, 2))
    lines = [f"#define {name}_W {w}", f"#define {name}_H {h}",
             f"static const uint8_t {name}_PX[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    return lines, f"{w} x {h}, {len(data)} B"


def main(out):
    im = ImageOps.invert(Image.open(SRC).convert("L"))          # the mark's ink as coverage
    im = im.point(lambda v: 0 if v < 40 else 255 if v > 215 else (v - 40) * 255 // 175)   # JPEG noise off
    im = im.crop(im.getbbox())
    lines, said = ["/* generated by tools/gen_logo.py from assets/logo.jpg */"], []
    for name, h in SIZES:
        l, s = bitmap(im, name, h)
        lines += l
        said.append(s)
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"gen_logo: {'; '.join(said)}")


if __name__ == "__main__":
    main(sys.argv[1])
