"""Render the Lunar Eclipse Forge logo (assets/logo.jpg, dark on light) to a C header for the boot
screen (gfx.c draw_splash): cropped to the mark, LOGO_H pixels tall, coverage 0..15, rows top to
bottom, 2 pixels per byte (high nibble first), as the font's glyphs.
"""
import sys
from pathlib import Path

from PIL import Image, ImageOps

SRC = Path(__file__).resolve().parents[1] / "assets" / "logo.jpg"
LOGO_H = 100


def main(out):
    im = ImageOps.invert(Image.open(SRC).convert("L"))          # the mark's ink as coverage
    im = im.point(lambda v: 0 if v < 40 else 255 if v > 215 else (v - 40) * 255 // 175)   # JPEG noise off
    im = im.crop(im.getbbox())
    w = round(im.width * LOGO_H / im.height)
    im = im.resize((w, LOGO_H), Image.LANCZOS)
    px = im.load()
    bpr = (w + 1) // 2
    data = bytearray()
    for y in range(LOGO_H):
        row = [min(15, (px[x, y] + 8) // 17) for x in range(w)] + [0]
        data += bytes((row[x] << 4) | row[x + 1] for x in range(0, bpr * 2, 2))
    lines = ["/* generated by tools/gen_logo.py from assets/logo.jpg */",
             f"#define LOGO_W {w}", f"#define LOGO_H {LOGO_H}",
             f"static const uint8_t LOGO_PX[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"gen_logo: {w} x {LOGO_H}, {len(data)} B")


if __name__ == "__main__":
    main(sys.argv[1])
