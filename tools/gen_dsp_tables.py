"""The effects' lookup tables (firmware/src/dsp/fxkit.h, fxbus.c), as flash-resident data:

  dsp_tables.h   the tanh lookup every saturator reads, and 9W9's EXP pot curves
                 (er99_pots.h: min * (max/min)^(pot/127)) evaluated here, so the device
                 needs no powf and gets the same values 9W9 computes with libm.

  tools/gen_dsp_tables.py build/gen/dsp_tables.h
"""
import math
import struct
import sys
from pathlib import Path

# 9W9's EXP pot ranges (er99_pots.h) that the effects use
EXP_RANGES = [("DRIVE", 0.85, 12.0), ("FX_HPF", 30.0, 800.0)]

TANH_N = 1024          # points over [0, TANH_MAX]; linear interpolation
TANH_MAX = 8.0


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def cfloat(x):
    s = repr(f32(x))
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def shared(ctype, name, dims, rows):
    """a table defined once (the unit that defines DSP_TABLES_DEFINE, dsp_tables.c), extern elsewhere"""
    return ["#ifdef DSP_TABLES_DEFINE", f"const {ctype} {name}{dims} = {{", *rows, "};",
            "#else", f"extern const {ctype} {name}{dims};", "#endif"]


def pot_exp(lo, hi, pot):
    """er99_pot_to_value for an EXP pot, in float as 9W9 evaluates it"""
    ratio = f32(f32(hi) / f32(lo))
    return f32(f32(lo) * f32(ratio ** f32(pot / 127.0)))


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "build/gen/dsp_tables.h")
    out.parent.mkdir(parents=True, exist_ok=True)
    tab = [f32(math.tanh(TANH_MAX * i / TANH_N)) for i in range(TANH_N + 2)]
    t = ["/* Generated by tools/gen_dsp_tables.py -- do not edit. */", "#pragma once", "",
         f"/* tanh(u) at u = i * {TANH_MAX} / {TANH_N}, i = 0..{TANH_N + 1} (one guard point) */",
         f"#define DSP_TANH_N {TANH_N}", f"#define DSP_TANH_SCALE {cfloat(TANH_N / TANH_MAX)}"]
    t += shared("float", "dsp_tanh_tab", f"[{len(tab)}]",
                ["    " + ", ".join(cfloat(v) for v in tab[i:i + 6]) + "," for i in range(0, len(tab), 6)])
    t += ["", "/* 9W9 EXP pots (er99_pots.h): value = min * (max/min)^(pot/127), pot 0..127 */"]
    t += [f"#define DSP_EXP_{n} {i}   /* {lo:g} .. {hi:g} */" for i, (n, lo, hi) in enumerate(EXP_RANGES)]
    rows = []
    for n, lo, hi in EXP_RANGES:
        vals = [pot_exp(lo, hi, p) for p in range(128)]
        rows += ["    { /* " + n + " */", *("        " + ", ".join(cfloat(v) for v in vals[i:i + 6]) + ","
                                            for i in range(0, 128, 6)), "    },"]
    t += shared("float", "dsp_pot_exp", f"[{len(EXP_RANGES)}][128]", rows) + [""]
    out.write_text("\n".join(t))
    print(f"gen_dsp_tables: tanh {TANH_N + 2} + {len(EXP_RANGES)} pot curves -> {out.name}")


if __name__ == "__main__":
    main()
