"""Render the screen's fonts to a C header: Barlow Semi Condensed (assets/fonts, SIL OFL 1.1),
anti-aliased, tabular figures (the OpenType `tnum` feature).

  XS  grid labels, units, hints      Barlow Semi Condensed SemiBold 12 px
  S   body                           Medium 15 px
  B   headers, names, the selected row   Bold 15 px
  M   knob values                    SemiBold 23 px (only the characters values use)

Glyph format: per glyph an advance width, a bitmap width and an offset; the
bitmap starts FONT_PAD pixels left of the pen position (room for side
bearings); rows top to bottom, 2 pixels per byte (high nibble first),
alpha 0..15.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path(__file__).resolve().parents[1] / "assets" / "fonts"
# (name, file, px, first, last)
SIZES = [("XS", "BarlowSemiCondensed-SemiBold.ttf", 12, 32, 126),
         ("S", "BarlowSemiCondensed-Medium.ttf", 15, 32, 126),
         ("B", "BarlowSemiCondensed-Bold.ttf", 15, 32, 126),
         ("M", "BarlowSemiCondensed-SemiBold.ttf", 23, 32, 95)]
PAD = 2
# the characters a face is ever drawn with, where that is fewer than its range: the others are
# empty (no width, no bitmap). M shows knob values that are words (OFF, C#3, 1/16, LP 40%).
KEEP = {"M": " #%+-./0123456789:ABCDEFGHIJKLMNOPQRSTUVWXYZ"}


def render(ttf, px, first, last):
    font = ImageFont.truetype(str(FONTS / ttf), px)
    feats = ["tnum"]
    asc, desc = font.getmetrics()
    top = max(0, font.getbbox("A8|(", features=feats)[1] - 1)
    h = asc + desc - top
    glyphs = []
    for c in range(first, last + 1):
        ch = chr(c)
        adv = int(round(font.getlength(ch, features=feats)))
        bw = adv + 2 * PAD
        img = Image.new("L", (bw, asc + desc), 0)
        ImageDraw.Draw(img).text((PAD, 0), ch, font=font, fill=255, features=feats)
        img = img.crop((0, top, bw, top + h))
        glyphs.append((adv, bw, [min(15, (v + 8) // 17) for v in img.tobytes()]))
    return h, glyphs


def main(out):
    lines = ["/* generated by tools/gen_font.py */",
             "#pragma once", "#include <stdint.h>", f"#define FONT_PAD {PAD}", ""]
    for name, ttf, px, first, last in SIZES:
        h, glyphs = render(ttf, px, first, last)
        if name in KEEP:
            glyphs = [g if chr(first + i) in KEEP[name] else (0, 0, []) for i, g in enumerate(glyphs)]
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536
        lines.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" +
                     ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" +
                     ", ".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const felucca_font_t FONT_{name} = {{ {h}, {PAD}, {first}, {last}, "
                     f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
        print(f"font {name}: {ttf} {px}px h {h}, digit adv {glyphs[ord('0') - first][0]}, {len(data)} B")
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
